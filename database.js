// Storage for the Addy server.
// With DATABASE_URL set (for example a Neon connection string) it uses PostgreSQL through the "pg" package.
// Without it, it uses a local SQLite file in DATA_DIR, which needs nothing installed.
// Both give the same small async interface: get / all / run, plus tx(fn) for a transaction.
// SQL is written once with ? placeholders and in a form both databases accept.
import fs from 'node:fs';
import path from 'node:path';

const SQLITE_SCHEMA = `
PRAGMA journal_mode = WAL;
PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS users(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  username TEXT UNIQUE NOT NULL COLLATE NOCASE,
  name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'collector',
  pass TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS projects(
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  classes TEXT NOT NULL,
  created_by INTEGER,
  created_at TEXT NOT NULL,
  updated_at INTEGER NOT NULL,
  archived INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS datasets(
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  data TEXT NOT NULL,
  deleted INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL,
  seq INTEGER NOT NULL,
  user_id INTEGER);
CREATE TABLE IF NOT EXISTS points(
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  data TEXT NOT NULL,
  deleted INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL,
  seq INTEGER NOT NULL,
  user_id INTEGER);
CREATE INDEX IF NOT EXISTS points_proj ON points(project_id, seq);
CREATE INDEX IF NOT EXISTS ds_proj ON datasets(project_id, seq);
CREATE TABLE IF NOT EXISTS meta(k TEXT PRIMARY KEY, v TEXT);
`;

// Same tables for PostgreSQL. Millisecond timestamps and sequence numbers need BIGINT.
const PG_SCHEMA = `
CREATE TABLE IF NOT EXISTS users(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'collector',
  pass TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS users_username ON users(lower(username));
CREATE TABLE IF NOT EXISTS sessions(
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE TABLE IF NOT EXISTS projects(
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  classes TEXT NOT NULL,
  created_by INTEGER,
  created_at TEXT NOT NULL,
  updated_at BIGINT NOT NULL,
  archived INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS datasets(
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  data TEXT NOT NULL,
  deleted INTEGER NOT NULL DEFAULT 0,
  updated_at BIGINT NOT NULL,
  seq BIGINT NOT NULL,
  user_id INTEGER);
CREATE TABLE IF NOT EXISTS points(
  id TEXT PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  data TEXT NOT NULL,
  deleted INTEGER NOT NULL DEFAULT 0,
  updated_at BIGINT NOT NULL,
  seq BIGINT NOT NULL,
  user_id INTEGER);
CREATE INDEX IF NOT EXISTS points_proj ON points(project_id, seq);
CREATE INDEX IF NOT EXISTS ds_proj ON datasets(project_id, seq);
CREATE TABLE IF NOT EXISTS meta(k TEXT PRIMARY KEY, v TEXT);
`;

export async function openDatabase({ url, dataDir }) {
  return url ? openPostgres(url) : openSqlite(dataDir);
}

async function openSqlite(dataDir) {
  const { DatabaseSync } = await import('node:sqlite');
  fs.mkdirSync(dataDir, { recursive: true });
  const file = path.join(dataDir, 'addy.db');
  const db = new DatabaseSync(file);
  db.exec(SQLITE_SCHEMA);
  const q = {
    get: async (sql, ...args) => db.prepare(sql).get(...args),
    all: async (sql, ...args) => db.prepare(sql).all(...args),
    run: async (sql, ...args) => { db.prepare(sql).run(...args); },
  };
  return {
    ...q,
    describe: `SQLite file ${file}`,
    // SQLite calls are synchronous, so nothing else runs between BEGIN and COMMIT.
    async tx(fn) {
      db.exec('BEGIN');
      try { const r = await fn(q); db.exec('COMMIT'); return r; }
      catch (e) { db.exec('ROLLBACK'); throw e; }
    },
  };
}

async function openPostgres(url) {
  let pg;
  try { pg = (await import('pg')).default; }
  catch { throw new Error('DATABASE_URL is set but the "pg" package is not installed. Run "npm install".'); }
  // BIGINT columns hold millisecond timestamps and counters, well inside the safe integer range.
  pg.types.setTypeParser(20, v => Number(v));
  const pool = new pg.Pool({ connectionString: url, max: Number(process.env.PG_POOL_MAX) || 5, idleTimeoutMillis: 30_000, connectionTimeoutMillis: 15_000 });
  // Neon closes idle connections; the pool replaces them, so just log it instead of crashing.
  pool.on('error', e => console.error('Database connection dropped:', e.message));
  let n;
  const toPg = sql => (n = 0, sql.replace(/\?/g, () => '$' + ++n));
  const wrap = c => ({
    get: async (sql, ...args) => (await c.query(toPg(sql), args)).rows[0],
    all: async (sql, ...args) => (await c.query(toPg(sql), args)).rows,
    run: async (sql, ...args) => { await c.query(toPg(sql), args); },
  });
  await pool.query(PG_SCHEMA);
  let host = 'PostgreSQL';
  try { host = new URL(url).host; } catch { /* keep the generic name */ }
  return {
    ...wrap(pool),
    describe: `PostgreSQL at ${host}`,
    async tx(fn) {
      const c = await pool.connect();
      let failed = false;
      try {
        await c.query('BEGIN');
        const r = await fn(wrap(c));
        await c.query('COMMIT');
        return r;
      } catch (e) {
        failed = true;
        await c.query('ROLLBACK').catch(() => {});
        throw e;
      } finally { c.release(failed); }
    },
  };
}
